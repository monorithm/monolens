/// The fixture's four quadrant colours, as the nearest-name buckets [_sample]
/// reports. Exact RGB would be brittle — JPEG shifts every value a little.
const String _red = 'red';
const String _green = 'green';
const String _blue = 'blue';
const String _yellow = 'yellow';

/// Decodes [path] and names the colour at the given fractional position.
Future<String> _sample(String path, double fx, double fy) async {
  final (r, g, b) = await _channels(path, fx, fy);
  const threshold = 128;
  return switch ((r > threshold, g > threshold, b > threshold)) {
    (true, false, false) => _red,
    (false, true, false) => _green,
    (false, false, true) => _blue,
    (true, true, false) => _yellow,
    _ => 'rgb($r,$g,$b)',
  };
}

/// The raw channels at a fractional position of a file on disk.
Future<(int, int, int)> _channels(String path, double fx, double fy) async =>
    _channelsOf(await File(path).readAsBytes(), fx, fy);

/// The raw channels at a fractional position of encoded bytes — which is how a
/// filmstrip frame arrives, and therefore how a video export is inspected.
Future<(int, int, int)> _channelsOf(
  Uint8List bytes,
  double fx,
  double fy,
) async {
  final codec = await ui.instantiateImageCodec(bytes);
  final image = (await codec.getNextFrame()).image;
  final data = await image.toByteData(format: ui.ImageByteFormat.rawRgba);
  final x = (fx * image.width).clamp(0, image.width - 1).toInt();
  final y = (fy * image.height).clamp(0, image.height - 1).toInt();
  final offset = (y * image.width + x) * 4;

  final r = data!.getUint8(offset);
  final g = data.getUint8(offset + 1);
  final b = data.getUint8(offset + 2);
  image.dispose();
  return (r, g, b);
}

/// True when the pixel is the sticker's magenta. Named rather than compared to
/// an exact triple because the still is a JPEG and every channel moves a little.
Future<bool> _magenta(String path, double fx, double fy) async {
  final (r, g, b) = await _channels(path, fx, fy);
  return r > 180 && g < 90 && b > 180;
}

/// Copies a bundled asset onto disk, since every native op works on file paths.
Future<String> _materialize(String asset) async {
  final directory = await MonolensPlatform.instance.cacheDirectory();
  final file = File('$directory/${asset.split('/').last}');
  await file.writeAsBytes(
    (await rootBundle.load(asset)).buffer.asUint8List(),
    flush: true,
  );
  return file.path;
}
